use crate::prelude::internal::*;
use relative_path::{PathExt, RelativePath};

impl<LangConfig: GtpLangConfig> GtlConfig<'_, LangConfig> {
    pub(crate) fn render_generated_warning_comment(
        &self,
        target_path: &GtpTargetFilePath,
        source_path: &RelativePath,
        relation: &str,
        comment_prefix: Option<&str>,
    ) -> Result<String, GtlProjectError> {
        let target_dir = target_path.relative_path().parent().ok_or_else(|| {
            GtlProjectError::GenerateTargetFile {
                path: target_path.clone(),
                error: "Failed to resolve the target file parent directory".into(),
            }
        })?;
        let source_path =
            relative_source_path(self.project.cwd_path().as_path(), target_dir, source_path)
                .map_err(|error| GtlProjectError::GenerateTargetFile {
                    path: target_path.clone(),
                    error: error.into(),
                })?;
        let comment = |content: &str| match comment_prefix {
            Some(prefix) => format!("{prefix} {content}"),
            None => self.lang_config().comment_line(content),
        };
        Ok(format!(
            "{}\n{}",
            comment(&format!(
                "Do not edit manually! The code is generated by `gt build` {relation} {source_path}"
            )),
            comment(r#"Use "genotype" agent skill if available."#),
        ))
    }

    pub(crate) fn render_extra_file_warning_comments(
        &self,
        dist: &mut GtlDist,
    ) -> Result<(), GtlProjectError> {
        if !self.warning_comment() {
            return Ok(());
        }
        for file in &mut dist.files {
            let GtlDistFile::Generated(file) = file else {
                continue;
            };
            if file.source_module_id.is_some() {
                continue;
            }
            let path = file.path.relative_path();
            let prefix = match (path.file_name(), path.extension()) {
                (Some(".gitignore"), _) | (_, Some("toml" | "py")) => "#",
                (_, Some("rs" | "ts")) => "//",
                _ => continue,
            };
            let warning = self.render_generated_warning_comment(
                &file.path,
                self.project_paths().config_file.relative_path(),
                "via",
                Some(prefix),
            )?;
            file.source_code =
                GtpSourceCode::new(format!("{warning}\n\n{}", file.source_code.content));
        }
        Ok(())
    }
}

fn relative_source_path(
    cwd: &std::path::Path,
    target_dir: &RelativePath,
    source_path: &RelativePath,
) -> Result<relative_path::RelativePathBuf, String> {
    // Resolve parent components against cwd so sibling output directories retain
    // the directory names needed to navigate back to the source.
    source_path
        .to_logical_path(cwd)
        .relative_to(target_dir.to_logical_path(cwd))
        .map_err(|error| format!("Failed to resolve the relative source path: {error}"))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn warning_uses_backend_working_directory() {
        for cwd in ["/virtual/project/pkgs/types", "/another/project/pkgs/types"] {
            let project = GtProject::try_new(
                cwd.into(),
                "types".into(),
                "genotype.toml".into(),
                GtpConfig::default(),
            )
            .unwrap();
            let config = GtlConfig::new(&project, &project.config().ts);
            for (target, expected) in [
                ("dist/ts/src/card.ts", "../../../src/card.type"),
                ("../npm/src/card.ts", "../../types/src/card.type"),
            ] {
                let warning = config
                    .render_generated_warning_comment(
                        &target.into(),
                        RelativePath::new("src/card.type"),
                        "from",
                        Some("//"),
                    )
                    .unwrap();
                assert_eq!(
                    warning,
                    format!(
                        "// Do not edit manually! The code is generated by `gt build` from {expected}\n// Use \"genotype\" agent skill if available."
                    )
                );
            }
        }
    }

    #[test]
    fn source_paths_outside_working_directory() {
        let cwd = GtpCwdPath::from("/virtual/project/pkgs/types");
        for (target, source, expected) in [
            ("../npm/src", "src/docs.type", "../../types/src/docs.type"),
            (
                "../cli/src/types",
                "src/docs.type",
                "../../../types/src/docs.type",
            ),
            ("../py/module", "src/docs.type", "../../types/src/docs.type"),
            (
                "../cli/src/types",
                "genotype.toml",
                "../../../types/genotype.toml",
            ),
            ("dist/ts/src", "src/docs.type", "../../../src/docs.type"),
            (
                "../npm/src",
                "../schemas/docs.type",
                "../../schemas/docs.type",
            ),
        ] {
            assert_eq!(
                relative_source_path(
                    cwd.as_path(),
                    RelativePath::new(target),
                    RelativePath::new(source)
                )
                .unwrap()
                .as_str(),
                expected,
            );
        }
    }
}
